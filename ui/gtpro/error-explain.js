  function explain(raw) {
    const text = String(raw == null ? "" : raw).trim();
    if (!text) return EMPTY_ERROR;
    const low = text.toLowerCase();
    for (const entry of CATALOG) {
      if (entry.patterns.some((p) => low.includes(p.toLowerCase()))) return entry;
    }
    return FALLBACK;
  }

  function stageLabel(stage) {
    const s = String(stage || "").trim();
    if (!s) return "";
    if (STAGE_LABELS[s]) return STAGE_LABELS[s];
    // dynamic KIE poll states (kie:<provider state>) → keep the state visible
    if (s.startsWith("kie:")) return `KIE: ${s.slice(4)}`;
    return s; // free-form extension stage strings pass through
  }

